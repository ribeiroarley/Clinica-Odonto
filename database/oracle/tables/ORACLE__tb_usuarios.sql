CREATE TABLE OWNER_ODONTO.TB_USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    SENHA_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL,
    CRO VARCHAR2(20),
    STATUS VARCHAR2(1) DEFAULT 'A' NOT NULL,
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    ATUALIZADO_EM DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_ROLE CHECK (ROLE IN ('ADMIN', 'DENTISTA', 'RECEPCAO')),
    CONSTRAINT CK_USUARIOS_STATUS CHECK (STATUS IN ('A', 'I'))
);

COMMENT ON TABLE OWNER_ODONTO.TB_USUARIOS IS 'Tabela de controle de credenciais e controle de acesso (RBAC) com hashes Argon2id.';
COMMENT ON COLUMN OWNER_ODONTO.TB_USUARIOS.ID_USUARIO IS 'Identificador unico do usuario.';
COMMENT ON COLUMN OWNER_ODONTO.TB_USUARIOS.NOME IS 'Nome do profissional ou operador do sistema.';
COMMENT ON COLUMN OWNER_ODONTO.TB_USUARIOS.EMAIL IS 'Email unico para login.';
COMMENT ON COLUMN OWNER_ODONTO.TB_USUARIOS.SENHA_HASH IS 'Hash seguro Argon2id da senha.';
COMMENT ON COLUMN OWNER_ODONTO.TB_USUARIOS.ROLE IS 'Perfil de acesso: ADMIN, DENTISTA ou RECEPCAO.';
COMMENT ON COLUMN OWNER_ODONTO.TB_USUARIOS.CRO IS 'Registro profissional do CRO (quando aplicavel).';
COMMENT ON COLUMN OWNER_ODONTO.TB_USUARIOS.STATUS IS 'Status da conta: A (Ativo) ou I (Inativo).';

CREATE TABLE OWNER_ODONTO.TB_AUDITORIA_IA (
    ID_AUDITORIA_IA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PACIENTE NUMBER NOT NULL REFERENCES OWNER_ODONTO.PACIENTES (ID_PACIENTE),
    ID_DENTISTA NUMBER NOT NULL REFERENCES OWNER_ODONTO.DENTISTAS (ID_DENTISTA),
    NOME_MODELO VARCHAR2(100) NOT NULL,
    VERSAO_MODELO VARCHAR2(50) NOT NULL,
    TIPO_CASO_USO VARCHAR2(50) NOT NULL, -- 'COPILOTO_ODONTOGRAMA', 'NO_SHOW_PREDICTION', etc.
    HASH_ENTRADA_ANONIMIZADA VARCHAR2(64) NOT NULL, -- Hash SHA-256 da entrada higienizada sem PII
    PAYLOAD_SUGESTAO_JSON CLOB NOT NULL,
    STATUS_DECISAO_HUMANA VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
    JUSTIFICATIVA_REJEICAO VARCHAR2(500),
    DATA_INFERENCIA DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CK_AUDITORIA_IA_DECISAO CHECK (STATUS_DECISAO_HUMANA IN ('PENDENTE', 'ACEITO', 'MODIFICADO', 'REJEITADO'))
);

COMMENT ON TABLE OWNER_ODONTO.TB_AUDITORIA_IA IS 'Trilha de auditoria imutavel (append-only) para explicabilidade, conformidade com o Art. 20 da LGPD (revisao humana) e requisitos de transparencia do EU AI Act (Art. 12 e 14).';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.ID_AUDITORIA_IA IS 'Identificador unico da recomendacao algoritmica.';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.ID_PACIENTE IS 'Paciente sujeito a assistencia clínica orientada por IA.';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.ID_DENTISTA IS 'Cirurgiao-dentista responsavel pela supervisao humana (Human-in-the-Loop).';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.NOME_MODELO IS 'Identificacao do modelo de IA (ex: Med-Dental-Copilot, YOLOv8-Dental).';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.VERSAO_MODELO IS 'Versao semantica do modelo para reprodutibilidade e MLOps.';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.TIPO_CASO_USO IS 'Dominio da inferencia (ex: COPILOTO_ODONTOGRAMA, PREVISAO_NO_SHOW).';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.HASH_ENTRADA_ANONIMIZADA IS 'Hash criptografico SHA-256 do prompt anonimizado, garantindo nao-repudio sem persistir dados pessoais.';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.PAYLOAD_SUGESTAO_JSON IS 'Estrutura JSON com as sugestoes geradas pelo modelo (faces, dentes e evidencias textuais).';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.STATUS_DECISAO_HUMANA IS 'Status da homologacao pelo dentista: PENDENTE, ACEITO, MODIFICADO ou REJEITADO.';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.JUSTIFICATIVA_REJEICAO IS 'Motivo clinico apontado pelo profissional humano em caso de discordancia ou descarte da sugestao.';
COMMENT ON COLUMN OWNER_ODONTO.TB_AUDITORIA_IA.DATA_INFERENCIA IS 'Data e hora exata do processamento da inferencia.';

CREATE TABLE OWNER_ODONTO.ODONTOGRAMA (
    ID_ODONTOGRAMA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PACIENTE NUMBER(10) NOT NULL,
    NUMERO_DENTE NUMBER(2) NOT NULL,
    STATUS_GERAL VARCHAR2(20) DEFAULT 'HIGIDO' NOT NULL,
    OBSERVACOES VARCHAR2(500),
    DATA_ATUALIZACAO DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_ODONTOGRAMA PRIMARY KEY (ID_ODONTOGRAMA),
    CONSTRAINT UK_ODONTO_PACIENTE_DENTE UNIQUE (ID_PACIENTE, NUMERO_DENTE),
    CONSTRAINT FK_ODONTO_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES OWNER_ODONTO.PACIENTES (ID_PACIENTE),
    CONSTRAINT CK_ODONTO_NUMERO_DENTE CHECK (
        (NUMERO_DENTE BETWEEN 11 AND 18) OR
        (NUMERO_DENTE BETWEEN 21 AND 28) OR
        (NUMERO_DENTE BETWEEN 31 AND 38) OR
        (NUMERO_DENTE BETWEEN 41 AND 48) OR
        (NUMERO_DENTE BETWEEN 51 AND 55) OR
        (NUMERO_DENTE BETWEEN 61 AND 65) OR
        (NUMERO_DENTE BETWEEN 71 AND 75) OR
        (NUMERO_DENTE BETWEEN 81 AND 85)
    ),
    CONSTRAINT CK_ODONTO_STATUS_GERAL CHECK (STATUS_GERAL IN ('HIGIDO', 'AUSENTE', 'IMPLANTE', 'PROTESE', 'ENDODONTIA', 'EM_TRATAMENTO'))
);

COMMENT ON TABLE OWNER_ODONTO.ODONTOGRAMA IS 'Mapeamento anatomico dental e status clinico geral de cada dente por paciente (Padrao FDI).';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA.ID_ODONTOGRAMA IS 'Identificador unico do registro no odontograma.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA.ID_PACIENTE IS 'Chave estrangeira vinculando ao paciente atendido.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA.NUMERO_DENTE IS 'Numero do dente segundo a numeracao internacional FDI (11..48 permanentes, 51..85 deciduos).';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA.STATUS_GERAL IS 'Estado clinico global do dente (HIGIDO, AUSENTE, IMPLANTE, PROTESE, ENDODONTIA, EM_TRATAMENTO).';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA.OBSERVACOES IS 'Observacoes clinicas relevantes sobre o dente.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA.DATA_ATUALIZACAO IS 'Data da ultima atualizacao do dente.';

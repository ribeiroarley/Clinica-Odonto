CREATE TABLE OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS (
    ID_ODONTO_PROC NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ODONTOGRAMA NUMBER NOT NULL,
    ID_PRONTUARIO NUMBER(10),
    ID_PROCEDIMENTO NUMBER(10) NOT NULL,
    FACE_DENTE VARCHAR2(5),
    ESTADO_FACE VARCHAR2(20) NOT NULL,
    VALOR_APLICADO NUMBER(10,2),
    DATA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_ODONTO_PROC PRIMARY KEY (ID_ODONTO_PROC),
    CONSTRAINT FK_ODONTO_PROC_ODONTOGRAMA FOREIGN KEY (ID_ODONTOGRAMA) REFERENCES OWNER_ODONTO.ODONTOGRAMA (ID_ODONTOGRAMA) ON DELETE CASCADE,
    CONSTRAINT FK_ODONTO_PROC_PRONTUARIO FOREIGN KEY (ID_PRONTUARIO) REFERENCES OWNER_ODONTO.PRONTUARIO_ELETRONICO (ID_PRONTUARIO),
    CONSTRAINT FK_ODONTO_PROC_PROCEDIMENTO FOREIGN KEY (ID_PROCEDIMENTO) REFERENCES OWNER_ODONTO.PROCEDIMENTOS (ID_PROCEDIMENTO),
    CONSTRAINT CK_ODONTO_PROC_FACE CHECK (FACE_DENTE IN ('V', 'L', 'P', 'M', 'D', 'O', 'I', 'GERAL')),
    CONSTRAINT CK_ODONTO_PROC_ESTADO CHECK (ESTADO_FACE IN ('CARIE', 'RESTAURADO', 'FRATURA', 'SELADO', 'CANAL')),
    CONSTRAINT CK_ODONTO_PROC_VALOR CHECK (VALOR_APLICADO IS NULL OR VALOR_APLICADO >= 0)
);

COMMENT ON TABLE OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS IS 'Historico e condicoes especificas por face do dente e procedimentos aplicados.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.ID_ODONTO_PROC IS 'Identificador unico do procedimento registrado na face/dente.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.ID_ODONTOGRAMA IS 'Chave estrangeira vinculando ao registro do dente.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.ID_PRONTUARIO IS 'Chave estrangeira opcional vinculando ao prontuario da consulta de realizacao.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.ID_PROCEDIMENTO IS 'Chave estrangeira vinculando ao catalogo de procedimentos odontologicos.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.FACE_DENTE IS 'Face anatomica tratada (V: Vestibular, L: Lingual, P: Palatina, M: Mesial, D: Distal, O: Oclusal, I: Incisal, GERAL).';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.ESTADO_FACE IS 'Patologia ou condicao da face (CARIE, RESTAURADO, FRATURA, SELADO, CANAL).';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.VALOR_APLICADO IS 'Valor financeiro cobrado para a intervencao especifica nesta face/dente.';
COMMENT ON COLUMN OWNER_ODONTO.ODONTOGRAMA_PROCEDIMENTOS.DATA_REGISTRO IS 'Data e hora do registro do procedimento.';
